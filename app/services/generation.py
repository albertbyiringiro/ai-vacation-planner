"""Generating an Itinerary with the model.

The slow call to the model happens with no database transaction open, so other requests are not
blocked behind it. The model's answer is untrusted text: it is parsed and validated strictly before
anything is stored, and the Trip is looked up again afterwards, because it may have changed."""

import logging
import threading
from collections.abc import Generator
from contextlib import contextmanager

from pydantic import BaseModel, ConfigDict, Field, ValidationError
from sqlalchemy.orm import Session

from app.llm.client import Effort, LLMClient, LLMResponse
from app.llm.errors import LLMUnusableAnswerError
from app.models import Itinerary, Trip
from app.prompts.itinerary import TripFacts, build_itinerary_prompt
from app.schemas.itineraries import DayData
from app.schemas.trips import MAX_TRIP_DAYS
from app.services import itineraries as itineraries_service
from app.services import trips as trips_service

logger = logging.getLogger("app.generation")

GENERATION_EFFORT: Effort = "low"


def max_tokens_for(days: int) -> int:
    """The most the model may write: room for a day's activities per day, plus a margin, capped.
    The cap also caps the cost of one call; trips longer than about 18 days may be cut off."""
    return min(8000, 800 + 400 * days)


MAX_GENERATED_DAYS = 18


class TripChanged(Exception):
    """The Trip changed while the itinerary was being generated, so the plan is for a trip that no
    longer exists."""


class TripTooLongToGenerate(Exception):
    """The Trip is longer than the model can plan in one reply."""


class GenerationInProgress(Exception):
    """This trip is already being generated by another request."""


_running: set[int] = set()
_running_lock = threading.Lock()


@contextmanager
def one_generation_at_a_time(trip_id: int) -> Generator[None]:
    """Refuse a second generation for a trip while the first runs: both would be paid for, and
    only one can be saved. (Within one process; a database error still covers the rest.)"""
    with _running_lock:
        if trip_id in _running:
            raise GenerationInProgress
        _running.add(trip_id)
    try:
        yield
    finally:
        with _running_lock:
            _running.discard(trip_id)


class GeneratedItinerary(BaseModel):
    model_config = ConfigDict(extra="forbid")

    days: list[DayData] = Field(min_length=1, max_length=MAX_TRIP_DAYS)


def parse_generated_days(response: LLMResponse, expected_days: int) -> list[DayData]:
    """The model's answer as validated days, or LLMUnusableAnswerError with a reason code."""

    if response.stop_reason == "max_tokens":
        raise LLMUnusableAnswerError("truncated")
    if response.stop_reason == "refusal":
        raise LLMUnusableAnswerError("refused")
    try:
        parsed = GeneratedItinerary.model_validate_json(response.text, strict=True)
    except ValidationError as error:
        invalid_json = any(e["type"] == "json_invalid" for e in error.errors())
        raise LLMUnusableAnswerError(
            "invalid_json" if invalid_json else "wrong_shape"
        ) from None

    numbers = sorted(day.day for day in parsed.days)

    if numbers != list(range(1, expected_days + 1)):
        raise LLMUnusableAnswerError("wrong_day_count")
    return parsed.days  # any order: the database returns days in day order


def generate_itinerary(db: Session, llm: LLMClient, trip: Trip) -> Itinerary:
    if trip.days > MAX_GENERATED_DAYS:
        raise TripTooLongToGenerate
    with one_generation_at_a_time(trip.id):
        return _generate(db, llm, trip)


def _generate(db: Session, llm: LLMClient, trip: Trip) -> Itinerary:
    facts = TripFacts.from_trip(trip)
    trip_id, owner_id, trip_days = trip.id, trip.owner_id, trip.days
    prompt = build_itinerary_prompt(facts)
    db.rollback()
    record = {"prompt_version": prompt.version, "trip_id": trip_id, "days": trip_days}
    try:
        response = llm.complete(
            prompt.messages,
            system=prompt.system,
            max_tokens=max_tokens_for(trip_days),
            effort=GENERATION_EFFORT,
        )

        days = parse_generated_days(response, trip_days)
    except LLMUnusableAnswerError as error:
        logger.warning(
            "itinerary_generation",
            extra={"fields": record | {"outcome": "unusable", "reason": error.reason}},
        )
        raise

    fresh = trips_service.get_owned_trip(db, owner_id, trip_id)
    if fresh is None:
        raise itineraries_service.TripVanished
    if TripFacts.from_trip(fresh) != facts:
        raise TripChanged
    itinerary = itineraries_service.replace_itinerary(db, fresh, days)
    logger.info("itinerary_generation", extra={"fields": record | {"outcome": "saved"}})
    return itinerary
